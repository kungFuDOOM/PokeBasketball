// Bundles the Pack Battles judge (src/multiplayer/shared/judgeMatch.ts, with the game engine and winnerCheck.ts) into
// one ES module for the pokejam-pack-judge Edge Function, which runs on Deno and can't import the app's sources.
// Run after changing the engine or the judge: `npm run build:judge`. A test fails while the committed bundle is stale.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

export const ENTRY = fileURLToPath(new URL('../src/multiplayer/shared/judgeMatch.ts', import.meta.url));
export const OUT = fileURLToPath(new URL('../supabase/functions/pokejam-pack-judge/judge.bundle.js', import.meta.url));

/** The bundle's text (without writing it), so the test can compare it with the committed file. */
export async function bundleText() {
  const r = await build({
    entryPoints: [ENTRY], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', write: false,
    legalComments: 'none', charset: 'utf8',
    // The app reads Vite's env in a few places; on the server it's a production build with nothing configured.
    define: { 'import.meta.env': '{"DEV":false,"PROD":true,"BASE_URL":"/","MODE":"production"}' },
    banner: { js: '// Generated by scripts/build-pack-judge.mjs from src/multiplayer/shared/judgeMatch.ts. Do not edit.' },
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { writeFileSync } = await import('node:fs');
  writeFileSync(OUT, await bundleText());
  console.log(`wrote ${OUT}`);
}
